function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

/** Build a fresh quiz: 5 random planets; kids get 2 hints & 3 options, adults 3 hints & 4 options. */
export function buildQuiz(mode: Mode, size = QUIZ_SIZE): QuizQuestion[] {
  const planets = shuffle(PLANETS).slice(0, size);
  return planets.map((planet) => {
    const pool = QUIZ_HINTS[planet.id]?.[mode] ?? [];
    const hints = shuffle(pool).slice(0, mode === "child" ? 2 : 3);
    const others = shuffle(PLANETS.filter((p) => p.id !== planet.id)).slice(
      0,
      mode === "child" ? 2 : 3
    );
    return { planet, hints, options: shuffle([planet, ...others]) };
  });
}

export function scoreMessage(score: number, mode: Mode): string {
  if (score >= QUIZ_SIZE)
    return mode === "child"
      ? "واای! همه را درست گفتی! تو یک ستاره‌شناس واقعی هستی!"
      : "بی‌نقص! همهٔ سیاره‌ها را می‌شناسی؛ یک ستاره‌شناس واقعی!";
  if (score === 4)
    return mode === "child"
      ? "عالی بود! فقط یکی را اشتباه گفتی."
      : "عالی! فقط یک قدم تا بی‌نقص بودن فاصله داشتی.";
  if (score === 3)
    return mode === "child"
      ? "خوب بود! کم‌کم داری ستاره‌شناس می‌شوی."
      : "خوب بود؛ با کمی تمرین بیشتر حرفه‌ای می‌شوی.";
  if (score === 2)
    return mode === "child"
      ? "اشکالی ندارد! دوباره بازی کن تا یاد بگیری."
      : "بد نبود؛ سیاره‌ها منتظر آشنایی بیشتر با تو هستند.";
  return mode === "child"
    ? "نگران نباش! سرنخ‌ها را دوباره بخوان و بازی کن."
    : "سفر تازه شروع شده؛ سرنخ‌ها را دوباره مرور کن.";
}
